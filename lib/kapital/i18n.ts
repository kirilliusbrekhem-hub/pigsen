export const DICT: Record<Lang, Dict> = { ru, en };
export const dictFor = (lang: Lang): Dict => DICT[lang];

function plural(n: number, one: string, few: string, many: string): string {
  const a = Math.abs(n) % 100;
  const b = a % 10;
  if (a > 10 && a < 20) return many;
  if (b === 1) return one;
  if (b >= 2 && b <= 4) return few;
  return many;
}

export const rub = (n: number, lang: Lang = "ru") => `${Math.round(n).toLocaleString(lang === "en" ? "en-US" : "ru-RU")} ₽`;
export const monthYear = (iso: string | null, lang: Lang) => {
  if (!iso) return "—";
  const s = new Date(iso).toLocaleDateString(lang === "en" ? "en-US" : "ru-RU", { month: "long", year: "numeric", timeZone: "UTC" }).replace(" г.", "");
  return s.charAt(0).toUpperCase() + s.slice(1);
};

