const TEMPLATE = /^(О чём урок|Какой из этих разделов|Что ещё разбирается|К какому курсу)/;

function valid(x: unknown): x is BankQuestion {
  const v = x as BankQuestion;
  return !!v && typeof v.q === "string" && v.q.length >= 5 && v.q.length <= 300 && Array.isArray(v.options) && v.options.length === 4 && v.options.every((o) => typeof o === "string" && o.length > 0 && o.length <= 200) && Number.isInteger(v.answer) && v.answer >= 0 && v.answer <= 3;
}

/** Questions from lesson quizzes people have taken (skipping lesson-specific template questions). */
async function lessonQuizQuestions(): Promise<BankQuestion[]> {
  const rows = await prisma.quizAttempt.findMany({ orderBy: { createdAt: "desc" }, take: 200, select: { questions: true } });
  const out: BankQuestion[] = [];
  const seen = new Set<string>();
  for (const r of rows) {
    let qs: unknown;
    try { qs = JSON.parse(r.questions); } catch { continue; }
    if (!Array.isArray(qs)) continue;
    for (const q of qs) {
      if (!valid(q) || TEMPLATE.test(q.q) || seen.has(q.q)) continue;
      seen.add(q.q);
      out.push({ q: q.q, options: q.options, answer: q.answer });
    }
  }
  return out;
}

function shuffle<T>(xs: T[]): T[] {
  const a = [...xs];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/** Picks `n` questions and shuffles option order; the answer index follows the shuffle. */
export async function pickQuestions(n: number): Promise<BankQuestion[]> {
  const extra = await lessonQuizQuestions().catch(() => []);
  const seen = new Set(CORE.map((q) => q.q));
  const pool = [...CORE, ...extra.filter((q) => !seen.has(q.q))];
  return shuffle(pool).slice(0, n).map((q) => {
    const order = shuffle([0, 1, 2, 3]);
    return { q: q.q, options: order.map((i) => q.options[i]), answer: order.indexOf(q.answer) };
  });
}
